/**
 * Regenerates app/data/sholat/kota.ts (Story 36): every Indonesian regency
 * (kabupaten) and city (kota) with coordinates, elevation, province, and
 * time zone, from Wikidata (CC0). Run manually when the list needs a
 * refresh:  node scripts/build-kota-data.mjs
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ENDPOINT = 'https://query.wikidata.org/sparql';
const sparql = async (query) => {
  const url = `${ENDPOINT}?query=${encodeURIComponent(query)}`;
  const response = await fetch(url, {
    headers: {
      Accept: 'application/sparql-results+json',
      'User-Agent': 'enem-landing-tools-build/1.0',
    },
  });
  if (!response.ok) throw new Error(`Wikidata ${response.status}`);
  return (await response.json()).results.bindings;
};

const REGENCY = 'Q3191695';
const CITY = 'Q3199141';

const main =
  await sparql(`SELECT ?item ?label ?provLabel ?lat ?lon ?type ?elev WHERE {
  VALUES ?type { wd:${REGENCY} wd:${CITY} }
  ?item wdt:P31 ?type ; p:P625/psv:P625 [ wikibase:geoLatitude ?lat ; wikibase:geoLongitude ?lon ] ;
        wdt:P131 ?prov . ?prov wdt:P31 wd:Q5098 .
  FILTER NOT EXISTS { ?item wdt:P576 ?end }
  OPTIONAL { ?item wdt:P2044 ?elev }
  ?item rdfs:label ?label FILTER(LANG(?label) = "id")
  ?prov rdfs:label ?provLabel FILTER(LANG(?provLabel) = "id")
}`);

// Jakarta's administrative cities use other Wikidata types.
const jakarta = await sparql(`SELECT ?item ?label ?lat ?lon ?elev WHERE {
  VALUES ?item { wd:Q10109 wd:Q10113 wd:Q10116 wd:Q10114 wd:Q10111 wd:Q10107 }
  ?item p:P625/psv:P625 [ wikibase:geoLatitude ?lat ; wikibase:geoLongitude ?lon ] .
  OPTIONAL { ?item wdt:P2044 ?elev }
  ?item rdfs:label ?label FILTER(LANG(?label) = "id")
}`);

const WITA = [
  'Bali',
  'Nusa Tenggara Barat',
  'Nusa Tenggara Timur',
  'Kalimantan Selatan',
  'Kalimantan Timur',
  'Kalimantan Utara',
  'Sulawesi Utara',
  'Sulawesi Tengah',
  'Sulawesi Selatan',
  'Sulawesi Tenggara',
  'Sulawesi Barat',
  'Gorontalo',
];
const WIT = [
  'Maluku',
  'Maluku Utara',
  'Papua',
  'Papua Barat',
  'Papua Barat Daya',
  'Papua Tengah',
  'Papua Pegunungan',
  'Papua Selatan',
];
const zona = (provinsi) =>
  WIT.includes(provinsi) ? 9 : WITA.includes(provinsi) ? 8 : 7;
const provinsiName = (label) =>
  label === 'Yogyakarta' ? 'DI Yogyakarta' : label;
const slugify = (text) =>
  text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

const seen = new Set();
const rows = [];
const push = (item, nama, provinsi, lat, lon, elev) => {
  if (seen.has(item)) return;
  seen.add(item);
  rows.push({
    nama,
    provinsi,
    lat: Math.round(lat * 1e4) / 1e4,
    lon: Math.round(lon * 1e4) / 1e4,
    elevasi: Math.max(0, Math.round(elev ?? 0)),
    zona: zona(provinsi),
  });
};

for (const row of main) {
  const isCity = row.type.value.endsWith(CITY);
  const label = row.label.value.replace(/^(Kota|Kabupaten)\s+/i, '');
  const provinsi = provinsiName(row.provLabel.value);
  push(
    row.item.value,
    `${isCity ? 'Kota' : 'Kabupaten'} ${label}`,
    provinsi,
    Number(row.lat.value),
    Number(row.lon.value),
    row.elev ? Number(row.elev.value) : 0,
  );
}
for (const row of jakarta) {
  const label = row.label.value;
  const nama =
    label === 'Kepulauan Seribu'
      ? 'Kabupaten Administrasi Kepulauan Seribu'
      : `Kota ${label}`;
  push(
    row.item.value,
    nama,
    'DKI Jakarta',
    Number(row.lat.value),
    Number(row.lon.value),
    row.elev ? Number(row.elev.value) : 0,
  );
}

rows.sort(
  (a, b) =>
    a.provinsi.localeCompare(b.provinsi, 'id') ||
    a.nama.localeCompare(b.nama, 'id'),
);
const slugCount = new Map();
const withSlug = rows.map((row) => {
  let slug = slugify(row.nama);
  const count = slugCount.get(slug) ?? 0;
  slugCount.set(slug, count + 1);
  if (count > 0) slug = `${slug}-${slugify(row.provinsi)}`;
  return { slug, ...row };
});

const out = `// Generated by scripts/build-kota-data.mjs from Wikidata (CC0) - do not edit by hand.
// ${new Date().toISOString().slice(0, 10)}: ${withSlug.length} kabupaten/kota.

export interface Kota {
  slug: string;
  nama: string;
  provinsi: string;
  lat: number;
  lon: number;
  /** Meters above sea level (0 when unknown). */
  elevasi: number;
  /** UTC offset: 7 (WIB), 8 (WITA), 9 (WIT). */
  zona: 7 | 8 | 9;
}

export const KOTA: Kota[] = ${JSON.stringify(withSlug)};
`;
const target = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'app',
  'data',
  'sholat',
  'kota.ts',
);
writeFileSync(target, out);
console.log(`Wrote ${withSlug.length} entries to ${target}`);
